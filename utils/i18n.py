def set_language(lang: str):
    """Switch UI language. Call `lang` = 'zh' or 'en'."""
    global _current_lang
    if lang in (LANG_ZH, LANG_EN):
        _current_lang = lang


def get_language() -> str:
    return _current_lang


def _(text: str) -> str:
    """Translate text to current language.

    If the current language is Chinese, return the text as-is.
    If English, look up the translation dictionary.
    Unknown strings are returned unchanged.
    """
    if _current_lang == LANG_ZH or not text:
        return text
    return _translations.get(text, text)
